// ---------------------------------------------------------------------------
// Build entries
// ---------------------------------------------------------------------------

function buildEntry(weekOf, category, item, price) {
  const now = new Date().toISOString();
  return {
    weekOf,
    entryId: randomUUID(),
    category,
    item,
    price,
    status: 'approved',
    purchased: true,
    createdBy: 'import',
    createdByName: 'Historical Import',
    createdAt: now,
    updatedAt: now,
  };
}

function buildAllEntries() {
  const entries = [];
  for (const [weekOf, items] of Object.entries(historicalData)) {
    for (const [category, item, price] of items) {
      entries.push(buildEntry(weekOf, category, item, price));
    }
  }
  return entries;
}

// ---------------------------------------------------------------------------
// DynamoDB operations
// ---------------------------------------------------------------------------

async function batchWrite(entries) {
  // BatchWrite supports max 25 items per request
  for (let i = 0; i < entries.length; i += 25) {
    const batch = entries.slice(i, i + 25);
    const putRequests = batch.map((item) => ({
      PutRequest: { Item: item },
    }));

    await docClient.send(
      new BatchWriteCommand({
        RequestItems: { [TABLE_NAME]: putRequests },
      })
    );
  }
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main() {
  console.log(`Importing historical data (May 2024 - Feb 2025) into ${TABLE_NAME}...`);
  console.log('NOTE: This does NOT delete existing items.\n');

  const allEntries = buildAllEntries();

  // Group by week for progress reporting
  const weekGroups = {};
  for (const entry of allEntries) {
    if (!weekGroups[entry.weekOf]) weekGroups[entry.weekOf] = [];
    weekGroups[entry.weekOf].push(entry);
  }

  const weeks = Object.keys(weekGroups).sort();
  console.log(`Found ${weeks.length} weeks with ${allEntries.length} total entries.\n`);

  let totalWritten = 0;
  for (const week of weeks) {
    const weekEntries = weekGroups[week];
    await batchWrite(weekEntries);
    totalWritten += weekEntries.length;
    console.log(`  Week ${week}: ${weekEntries.length} items written (${totalWritten}/${allEntries.length} total)`);
  }

  console.log(`\nDone! Successfully imported ${allEntries.length} entries across ${weeks.length} weeks.`);
}

main().catch((err) => {
  console.error('Import failed:', err);
  process.exit(1);
});
